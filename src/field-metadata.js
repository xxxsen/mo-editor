const normalize = value => String(value ?? '').trim().toLowerCase();
const index = entries => new Map(Object.entries(entries).map(([name, definition]) => [normalize(name), definition]));
const tables = Object.fromEntries(Object.entries(FIELD_METADATA)
  .filter(([name]) => name !== 'sections').map(([name, entries]) => [name, index(entries)]));
const sections = Object.fromEntries(Object.entries(FIELD_METADATA.sections).map(([name, entries]) => [name, index(entries)]));
const technoTypes = new Set(['infantry', 'vehicle', 'aircraft', 'building']);
const difficultySections = new Set(['easy', 'normal', 'difficult']);
const technoOnlyEffects = new Set(['attacheffect.delay', 'attacheffect.initialdelay']);
const warheadOnlyEffects = new Set(['attacheffect.cumulative']);

// type 对应编辑器对象类型；section 是原始 INI 段名，globalKind 区分国家段。
export function getFieldInfo(fieldName, { type = '', section = '', globalKind = '' } = {}) {
  const name = normalize(fieldName);
  const sectionName = normalize(section);
  let definition;
  if (type === 'global' || type === 'sections') {
    const sectionTable = difficultySections.has(sectionName) ? sections.difficulty : sections[sectionName];
    definition = sectionTable?.get(name);
    if (!definition && globalKind === 'country') definition = tables.country.get(name) || tables.common.get(name);
    if (!definition && sectionName === 'general') definition = tables.common.get(name);
  } else if (technoTypes.has(type)) {
    definition = tables.techno.get(name) || (!warheadOnlyEffects.has(name) && tables.attachEffect.get(name)) || tables.common.get(name);
    if (!definition) {
      let match = fieldName.match(/^(Elite)?Weapon(\d+)$/i);
      if (match) definition = [`${match[1] ? '精英' : ''}第 ${Number(match[2])} 武器`, `对象${match[1] ? '达到精英等级时' : ''}使用的第 ${Number(match[2])} 个编号武器 ID。`];
      else if ((match = fieldName.match(/^WeaponTurretIndex([1-9]\d*)$/i))) {
        definition = [`第 ${Number(match[1])} 武器炮塔索引`, `多炮塔或多功能步兵车模式下，第 ${Number(match[1])} 个编号武器对应的炮塔索引。`];
      } else if ((match = fieldName.match(/^(Elite)?Stage([1-9]\d*)$/i))) {
        definition = [`${match[1] ? '精英' : ''}加特林第 ${Number(match[2])} 阶段阈值`, `加特林${match[1] ? '精英等级' : '普通等级'}第 ${Number(match[2])} 阶段使用的开火计时阈值；需配合 WeaponStages 和武器编号。`];
      } else if ((match = fieldName.match(/^BurstDelay(\d+)$/i))) {
        definition = [`连发间隔 ${Number(match[1])}`, `编号从 0 开始的连发射击间隔，单位为帧。原版支持载具的 0 至 3；其他编号或对象类型是否生效取决于扩展。`];
      } else if ((match = fieldName.match(/^Survivor\.Side(\d+)$/i))) {
        definition = [`阵营 ${Number(match[1])} 逃生驾驶员`, `载具或飞机属于阵营索引 ${Number(match[1])} 时，可生成的逃生驾驶员步兵类型 ID；阵营索引从 0 开始。`];
      }
    }
  } else if (type === 'weapon' || type === 'warhead' || type === 'superweapon') {
    definition = tables[type].get(name) || (type === 'warhead' && !technoOnlyEffects.has(name) ? tables.attachEffect.get(name) : null) || tables.common.get(name);
    if (!definition && type === 'warhead') {
      const match = fieldName.match(/^Versus\.([^.]+)(?:\.(ForceFire|Retaliate|PassiveAcquire))?$/i);
      if (match) {
        const armor = match[1], behavior = normalize(match[2]);
        const behaviors = {
          forcefire: ['强制攻击', '是否允许强制攻击此装甲类型的对象。'],
          retaliate: ['受击反击', '是否允许使用此弹头反击此装甲类型的对象。'],
          passiveacquire: ['自动索敌', '是否允许使用此弹头自动选取此装甲类型的对象。'],
        };
        definition = behavior ? [`装甲 ${armor} ${behaviors[behavior][0]}`, behaviors[behavior][1]]
          : [`装甲 ${armor} 伤害倍率`, `此弹头对 ${armor} 装甲的伤害倍率；特殊倍率还可能影响选敌与反击。`];
      }
    }
    if (!definition && type === 'superweapon') {
      const match = fieldName.match(/^ParaDrop\.(?:.+\.)?(Types|Num|Aircraft|Count)$/i);
      if (match) {
        const base = tables.superweapon.get(`paradrop.${normalize(match[1])}`);
        if (base) definition = [base[0], `${base[1]} 此字段使用的国家、阵营或飞机编号由字段名中的前缀指定。`];
      }
    }
  }
  if (!definition) return { label: fieldName, description: '', aliases: [], known: false, inlineHint: false };
  const [label, description, aliases = [], inlineHint = false] = definition;
  return { label, description, aliases, known: true, inlineHint };
}
